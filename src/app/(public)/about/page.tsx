export default async function AboutPage() {
  const contentData = await getAboutContentAction();
  const rawText = contentData?.text || DEFAULT_TEXT;

  // Split by newlines, filter empty lines
  const paragraphs = rawText.split('\n').map(p => p.trim()).filter(p => p.length > 0);

  return (
    <div className="pt-32 pb-24 relative overflow-hidden" dir="rtl">
      {/* Subtle background decoration */}
      <div className="absolute top-0 right-0 w-full h-full opacity-[0.03] pointer-events-none" 
           style={{
             backgroundImage: 'url("/logo-last.png")',
             backgroundRepeat: 'repeat',
             backgroundSize: '400px',
             backgroundPosition: 'center',
           }}
      />
      
      <div className="max-w-4xl mx-auto px-4 md:px-8 relative z-20">
        
        <div className="text-center mb-16 fade-in">
          <h1 className="text-4xl md:text-6xl font-black text-slate-900 mb-6 relative inline-block">
            من نحن
            <span className="absolute -bottom-4 left-1/2 -translate-x-1/2 w-24 h-1 bg-[#b18c39] rounded-full"></span>
          </h1>
        </div>

        <div className="bg-white/80 backdrop-blur-xl rounded-3xl p-8 md:p-16 shadow-[0_20px_60px_-15px_rgba(0,0,0,0.05)] border border-slate-100/50">
          <div className="space-y-8 text-lg md:text-xl xl:text-2xl font-medium text-slate-800 leading-relaxed md:leading-[2.2] text-justify" style={{ textJustify: 'inter-character' }}>
            {paragraphs.map((paragraph, idx) => {
              // Highlight poetic short lines by centering them
              const isShortLine = paragraph.length < 80 && !paragraph.includes('صنعاء') && !paragraph.includes('يكتبه');
              
              // Highlight signature
              if (paragraph.includes('صنعاء') && paragraph.includes('2015')) {
                return (
                  <div key={idx} className="pt-12 text-left text-slate-500 font-bold fade-in" style={{ animationDelay: (idx * 100) + 'ms' }}>
                    {paragraph}
                  </div>
                );
              }

              if (paragraph.includes('من نحن  .. ؟  يكتبه - عبدالملك المخلافي:')) {
                  return (
                      <div key={idx} className="pb-8 text-center text-[#b18c39] font-black text-2xl md:text-3xl fade-in" style={{ animationDelay: (idx * 100) + 'ms' }}>
                        {paragraph}
                      </div>
                  );
              }

              if (isShortLine) {
                return (
                  <p key={idx} className="text-center font-bold text-[#b18c39] fade-in" style={{ animationDelay: (idx * 100) + 'ms' }}>
                    {paragraph}
                  </p>
                );
              }

              return (
                <p key={idx} className="fade-in" style={{ animationDelay: (idx * 100) + 'ms' }}>
                  {paragraph}
                </p>
              );
            })}
          </div>
        </div>
      </div>
    </div>
  );
}
